export type FontRole = "display" | "text" | "condensed" | "mono";
export type LicenseId = "brygada" | "fira-sans" | "fira-condensed" | "plex-mono" | "noto-mono";

export interface FontFace {
  /** Family name as written in `font-family`. */
  readonly family: string;
  readonly weight: 400 | 500 | 600 | 700;
  readonly role: FontRole;
  /** Base of the file name: `<slug>-<weight>.woff2` (site) and `.ttf` (PDF; react-pdf cannot read woff2). */
  readonly slug: string;
  readonly license: LicenseId;
}


/** Text of `styles/fonts.css`: one `@font-face` per face, relative to `src/styles/`. */
export function fontFaceCss(): string {
  const head = "/* Generated by packages/ui/scripts/build-css.mjs from src/fonts/catalog.ts. Do not edit by hand. */\n";
  const rules = fontFaces.map((f) =>
    [
      "@font-face {",
      `  font-family: "${f.family}";`,
      "  font-style: normal;",
      `  font-weight: ${f.weight};`,
      "  font-display: swap;",
      `  src: url("../../fonts/${fontFile(f, "woff2")}") format("woff2");`,
      "}",
    ].join("\n"),
  );
  return `${head}\n${rules.join("\n\n")}\n`;
}

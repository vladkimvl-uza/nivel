// Bakes the boolean geometry of the intro "Fit to tolerance" into src/logo-motion/geometry-data.ts:
//   - the word "nivel" as one rigid part (the union of its overlapping subpaths: "n" is a stem and an arch, "e" a
//     ring and a bar);
//   - the plate: a rectangle minus the union of all parts, i.e. the pockets along the lockup contour.
// The site never runs this: the file is checked in, so the browser needs no polygon library (concept notes, risks).
// The result is checked by src/logo-motion/geometry.test.ts against the SVG outlines, so it cannot drift.
//
// The package polygon-clipping is NOT a dependency of the repository (no dependency without the integrator).
// To rebuild, install it anywhere outside the repo and point POLYGON_CLIPPING at its ES build:
//   npm i polygon-clipping@0.15.7 --prefix <tmp>
//   POLYGON_CLIPPING=<tmp>/node_modules/polygon-clipping/dist/polygon-clipping.esm.js \
//     pnpm exec node packages/ui/scripts/bake-logo-geometry.mjs
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { lockupOutlines } from "../src/logo-motion/outline.ts";

const target = fileURLToPath(new URL("../src/logo-motion/geometry-data.ts", import.meta.url));
const modulePath = process.env.POLYGON_CLIPPING;
if (!modulePath) {
  console.error(
    "bake-logo-geometry: set POLYGON_CLIPPING to polygon-clipping/dist/polygon-clipping.esm.js (see the header)",
  );
  process.exit(1);
}
const pc = (await import(pathToFileURL(modulePath).href)).default;

const DIGITS = 4;
const round = (v) => Number(v.toFixed(DIGITS));
const open = (ring) => ring.slice(0, -1).map(([x, y]) => [round(x), round(y)]);
const closed = (ring) => [...ring, ring[0]];

const o = lockupOutlines();
const word = pc.union(...o.wordParts.map((r) => [closed(r)]));
// the plate is larger than any frame (the widest is 9:16 on a phone); the pockets are the lockup contour
const rect = [
  [
    [-2000, -1600],
    [2400, -1600],
    [2400, 1700],
    [-2000, 1700],
    [-2000, -1600],
  ],
];
const parts = [o.shelf, o.triLeft, o.triRight, o.line, o.dot].map((r) => [closed(r)]);
const plate = pc.difference(rect, ...parts, ...word);

const polygons = (mp) => mp.map((poly) => poly.map(open));
const body = JSON.stringify({ rect: open(rect[0]), word: polygons(word), plate: polygons(plate) });
writeFileSync(
  target,
  [
    "// Generated by packages/ui/scripts/bake-logo-geometry.mjs: do not edit by hand.",
    "// Boolean geometry of the lockup in scene units (Y up): `word` is the union of the subpaths of the word,",
    "// `plate` is the plate with pockets (rectangle minus all parts). Each polygon is [outer, ...holes], rings are open.",
    'import type { Ring } from "./outline.ts";',
    "",
    "export interface GeometryData {",
    "  readonly rect: Ring;",
    "  readonly word: readonly (readonly Ring[])[];",
    "  readonly plate: readonly (readonly Ring[])[];",
    "}",
    "",
    `export const geometryData: GeometryData = ${body};`,
    "",
  ].join("\n"),
);
const fmt = spawnSync(`pnpm exec biome format --write "${target}"`, { stdio: "inherit", shell: true });
if (fmt.status !== 0) process.exit(fmt.status ?? 1);
console.info(
  `logo-motion: wrote src/logo-motion/geometry-data.ts (word polygons ${word.length}, plate polygons ${plate.length})`,
);

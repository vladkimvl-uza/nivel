// Builds dist/Nivel-CRM.gs: all the sources in one file for pasting into the Apps Script editor, in the load order.
// Usage: node scripts/bundle.mjs [--out <file>] [--check]   (--check fails if the file on disk is stale)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { SRC_DIR, sourceFiles } from "./load.mjs";

const here = dirname(fileURLToPath(import.meta.url));
export const DIST_DIR = join(here, "..", "dist");

/** The text of the bundle: a banner and the sources, each under its own marker. */
export function buildBundle() {
  const parts = [
    "// Nivel CRM for Google Sheets: Apps Script (V8), one file.",
    "// Generated by tools/crm-sheets/scripts/bundle.mjs from tools/crm-sheets/src/*.js. Do not edit by hand: change src and build again.",
    "// The manifest (time zone, scopes, web app) is in appsscript.json next to this file.",
    "",
  ];
  for (const f of sourceFiles()) {
    parts.push(`// ===== ${f} =====`);
    parts.push(readFileSync(join(SRC_DIR, f), "utf8").replace(/\r\n/g, "\n").trimEnd());
    parts.push("");
  }
  return `${parts.join("\n")}\n`;
}

/** The manifest as it must be next to the bundle. */
export function manifestText() {
  return readFileSync(join(SRC_DIR, "appsscript.json"), "utf8").replace(/\r\n/g, "\n");
}

export function writeBundle(dir = DIST_DIR) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "Nivel-CRM.gs"), buildBundle());
  writeFileSync(join(dir, "appsscript.json"), manifestText());
  return dir;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { out: { type: "string" }, check: { type: "boolean" } } });
  const dir = values.out ? resolve(values.out) : DIST_DIR;
  if (values.check) {
    let stale = false;
    try {
      stale = readFileSync(join(dir, "Nivel-CRM.gs"), "utf8") !== buildBundle();
    } catch {
      stale = true;
    }
    if (stale) {
      console.error("dist/Nivel-CRM.gs is stale: run node tools/crm-sheets/scripts/bundle.mjs");
      process.exit(1);
    }
    console.log("dist/Nivel-CRM.gs is current");
  } else {
    console.log(`bundle: ${writeBundle(dir)}`);
  }
}
